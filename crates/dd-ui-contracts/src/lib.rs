fn parse_decimal<T: FromStr + Display>(encoded: &str) -> Result<T, &'static str> {
    let value: T = encoded
        .parse()
        .map_err(|_| "integer is malformed or out of range")?;
    if value.to_string() != encoded {
        return Err("integer string is not canonical");
    }
    Ok(value)
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize, TS)]
#[serde(try_from = "String", into = "String")]
#[ts(type = "string")]
pub struct UuidText(String);

impl TryFrom<String> for UuidText {
    type Error = &'static str;

    fn try_from(value: String) -> Result<Self, Self::Error> {
        if value.len() != 36
            || !value.bytes().enumerate().all(|(index, byte)| match index {
                8 | 13 | 18 | 23 => byte == b'-',
                _ => byte.is_ascii_hexdigit(),
            })
        {
            return Err("expected a hyphenated UUID");
        }
        Ok(Self(value))
    }
}

impl From<UuidText> for String {
    fn from(value: UuidText) -> Self {
        value.0
    }
}

