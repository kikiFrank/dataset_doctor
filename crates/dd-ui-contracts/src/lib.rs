//! Tauri message contracts shared with the desktop frontend.

use std::fmt::Display;
use std::str::FromStr;

use serde::{Deserialize, Serialize};
use ts_rs::{Config, TS};

#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize, TS)]
#[serde(try_from = "String", into = "String")]
#[ts(type = "string")]
pub struct DecimalU64(u64);

impl TryFrom<String> for DecimalU64 {
    type Error = &'static str;

    fn try_from(encoded: String) -> Result<Self, Self::Error> {
        parse_decimal(&encoded).map(Self)
    }
}

impl From<DecimalU64> for String {
    fn from(value: DecimalU64) -> Self {
        value.0.to_string()
    }
}

#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize, TS)]
#[serde(try_from = "String", into = "String")]
#[ts(type = "string")]
pub struct DecimalI64(i64);

impl TryFrom<String> for DecimalI64 {
    type Error = &'static str;

    fn try_from(encoded: String) -> Result<Self, Self::Error> {
        parse_decimal(&encoded).map(Self)
    }
}

impl From<DecimalI64> for String {
    fn from(value: DecimalI64) -> Self {
        value.0.to_string()
    }
}

fn parse_decimal<T: FromStr + Display>(encoded: &str) -> Result<T, &'static str> {
    let value: T = encoded
        .parse()
        .map_err(|_| "integer is malformed or out of range")?;
    if value.to_string() != encoded {
        return Err("integer string is not canonical");
    }
    Ok(value)
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize, TS)]
#[serde(try_from = "String", into = "String")]
#[ts(type = "string")]
pub struct UuidText(String);

impl TryFrom<String> for UuidText {
    type Error = &'static str;

    fn try_from(value: String) -> Result<Self, Self::Error> {
        if value.len() != 36
            || !value.bytes().enumerate().all(|(index, byte)| match index {
                8 | 13 | 18 | 23 => byte == b'-',
                _ => byte.is_ascii_hexdigit(),
            })
        {
            return Err("expected a hyphenated UUID");
        }
        Ok(Self(value))
    }
}

impl From<UuidText> for String {
    fn from(value: UuidText) -> Self {
        value.0
    }
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize, TS)]
#[serde(
    tag = "kind",
    content = "id",
    rename_all = "SCREAMING_SNAKE_CASE",
    deny_unknown_fields
)]
pub enum ArtifactOwner {
    Task(UuidText),
    Asset(UuidText),
    Review(UuidText),
}

pub fn wire_primitives_typescript() -> String {
    let config = Config::default();
    let mut output = String::from("// Generated by dd-ui-contracts. Edit the Rust DTO source.\n");
    for declaration in [
        DecimalU64::decl(&config),
        DecimalI64::decl(&config),
        UuidText::decl(&config),
        ArtifactOwner::decl(&config),
    ] {
        output.push_str("\nexport ");
        output.push_str(&declaration);
        output.push('\n');
    }
    output
}
